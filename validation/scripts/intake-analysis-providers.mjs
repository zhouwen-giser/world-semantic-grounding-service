import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const upstream = process.argv[2];
if (!upstream) throw new Error("Usage: node validation/scripts/intake-analysis-providers.mjs <read-only repository>");
const branch = "codex/metric-ranking-provider-v0.1";
const git = (...args) => execFileSync("git", ["-C", upstream, ...args]);
const commit = git("rev-parse", `origin/${branch}`).toString().trim();
const tree = git("rev-parse", `${commit}^{tree}`).toString().trim();
const root = resolve("contracts/upstream/gowm-analysis-providers-current");
const hash = bytes => `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
const paths = git("ls-tree", "-r", "--name-only", commit).toString().trim().split("\n").filter(path =>
  path.startsWith("contracts/") && path.endsWith(".json") ||
  path.startsWith("integration/gowm/") && path.endsWith(".json") ||
  /^packages\/(trajectory|temporal-events|metric-ranking)-model\/src\/index.ts$/.test(path));
const files = [];
for (const path of paths) {
  const bytes = git("show", `${commit}:${path}`);
  const destination = resolve(root, path);
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, bytes);
  files.push({ path, sha256: hash(bytes) });
}
const source = { schemaVersion: "1.0", repository: "zhouwen-giser/gowm-spatiotemporal-analysis-providers",
  branch, commit, tree, capturedAt: new Date().toISOString(), files };
const bytes = `${JSON.stringify(source, null, 2)}\n`;
writeFileSync(resolve(root, "source.json"), bytes);
writeFileSync("packages/gowm-contract-intake/src/analysis-source.generated.ts",
  `// Generated by intake-analysis-providers.mjs from fetched upstream Git objects.\nexport const ANALYSIS_SOURCE_HASH = "${hash(bytes)}" as const;\n`);
for (const name of ["trajectory", "temporal-events", "metric-ranking"]) {
  const path = `packages/${name}-model/src/index.ts`;
  const text = readFileSync(resolve(root, path), "utf8").replaceAll("../../trajectory-model/src/index.js", "./trajectory.js").split("export const clamp01")[0];
  const destination = `packages/gowm-contract-intake/src/analysis-models/${name}.ts`;
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, `// Generated type-only projection of ${path}; source bytes recorded in intake.\n${text}`);
}
process.stdout.write(`${JSON.stringify({ commit, tree, files: files.length, sourceHash: hash(bytes) })}\n`);
