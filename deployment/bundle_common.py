"""Deterministic source archives with complete inventories and safe extraction."""
import gzip
import hashlib
import io
from pathlib import Path, PurePosixPath
import re
import tarfile


def sha(data):
    return hashlib.sha256(data).hexdigest()


def safe_name(name):
    name = name.removeprefix('./').rstrip('/')
    path = PurePosixPath(name)
    if not name or path.is_absolute() or '..' in path.parts or '\\' in name or any(c in name for c in '\r\n\0'):
        raise ValueError('Unsafe archive path: ' + repr(name))
    return str(path)


def read_archive(source):
    data = source if isinstance(source, bytes) else Path(source).read_bytes()
    files, modes, seen, roots = {}, {}, set(), set()
    total = 0
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
        for entry in archive:
            name = safe_name(entry.name)
            if name in seen or entry.mode & 0o7000 or not (entry.isfile() or entry.isdir()):
                raise ValueError('Unsafe or duplicate archive member: ' + name)
            seen.add(name)
            roots.add(name.split('/')[0])
            if entry.isfile():
                total += entry.size
                if total > 2 * 1024**3:
                    raise ValueError('Expanded archive exceeds 2 GiB')
                files[name] = archive.extractfile(entry).read()
                modes[name] = entry.mode & 0o777
    if len(roots) != 1:
        raise ValueError('Archive must have one root')
    root = roots.pop()
    if any(not name.startswith(root + '/') for name in files):
        raise ValueError('Archive root must be a directory')
    files = {name[len(root) + 1:]: data for name, data in files.items()}
    modes = {name[len(root) + 1:]: mode for name, mode in modes.items()}
    # A file cannot also be an ancestor directory of another file.
    if any(str(parent) in files for name in files for parent in PurePosixPath(name).parents if str(parent) != '.'):
        raise ValueError('Archive file/directory conflict')
    listed = {}
    if 'SHA256SUMS' not in files:
        raise ValueError('Archive checksum inventory is missing')
    for line in files.get('SHA256SUMS', b'').decode().splitlines():
        match = re.fullmatch(r'([0-9a-f]{64}) [ *](.+)', line)
        if not match:
            raise ValueError('Invalid checksum line')
        name = safe_name(match[2])
        if name in listed:
            raise ValueError('Duplicate checksum entry')
        listed[name] = match[1]
    if set(listed) != set(files) - {'SHA256SUMS'}:
        raise ValueError('Archive checksum inventory is incomplete')
    for name, digest in listed.items():
        if sha(files[name]) != digest:
            raise ValueError('Archive checksum mismatch: ' + name)
    return root, files, modes


def checked_package(path):
    path = Path(path)
    def signature(item):
        info = item.stat()
        return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns
    before = (signature(path), signature(path.with_name(path.name + '.sha256')))
    data = path.read_bytes()
    line = path.with_name(path.name + '.sha256').read_text().strip()
    after = (signature(path), signature(path.with_name(path.name + '.sha256')))
    if before != after or line != sha(data) + '  ' + path.name:
        raise ValueError('Package changed or its external checksum is invalid: ' + path.name)
    return data, read_archive(data)


def write_archive(path, root, files, modes=None):
    path, root = Path(path), safe_name(root)
    if '/' in root:
        raise ValueError('Archive root must be a single name')
    files = dict(files)
    if 'SHA256SUMS' in files:
        raise ValueError('Checksum inventory is generated by the archiver')
    for name in files:
        if safe_name(name) != name:
            raise ValueError('Noncanonical file name')
    files['SHA256SUMS'] = ''.join(f'{sha(data)}  ./{name}\n' for name, data in sorted(files.items())).encode()
    directories = {root}
    for name in files:
        directories.update(str(parent) for parent in (PurePosixPath(root) / name).parents if str(parent) != '.')
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name('.' + path.name + '.tmp')
    with temporary.open('wb') as raw, gzip.GzipFile(filename='', fileobj=raw, mode='wb', mtime=0) as compressed, tarfile.open(fileobj=compressed, mode='w') as archive:
        for name in sorted(directories):
            info = tarfile.TarInfo(name)
            info.type, info.mode = tarfile.DIRTYPE, 0o755
            archive.addfile(info)
        for name, data in sorted(files.items()):
            info = tarfile.TarInfo(root + '/' + name)
            info.size = len(data)
            info.mode = 0o755 if (modes or {}).get(name, 0o644) & 0o111 else 0o644
            archive.addfile(info, io.BytesIO(data))
    read_archive(temporary)
    temporary.replace(path)
    digest = sha(path.read_bytes())
    checksum = path.with_name(path.name + '.sha256')
    temporary = checksum.with_name('.' + checksum.name + '.tmp')
    temporary.write_text(f'{digest}  {path.name}\n')
    temporary.replace(checksum)
    return digest


def extract(source, destination):
    root, files, modes = read_archive(source)
    destination = Path(destination).resolve()
    destination.mkdir(parents=True, exist_ok=True, mode=0o700)
    target = destination / root
    if target.exists() or target.is_symlink():
        raise ValueError('Extraction destination exists')
    target.mkdir(mode=0o755)
    for name, data in files.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        path.chmod(modes[name])
    return target


def verify_tree(source, destination):
    """Bind a cached extraction to this archive, allowing generated runtime files."""
    root, files, modes = read_archive(source)
    destination = Path(destination).resolve()
    if destination.name != root:
        raise ValueError('Extracted source root differs from archive')
    for name, data in files.items():
        path = destination / name
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(destination):
            raise ValueError('Extracted source entry is missing or unsafe: ' + name)
        if sha(path.read_bytes()) != sha(data) or path.stat().st_mode & 0o777 != modes[name]:
            raise ValueError('Extracted source differs from this package: ' + name)
    return root
